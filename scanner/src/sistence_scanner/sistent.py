"""Running con/sistent over the resolved repositories and reading its JSON report."""

from __future__ import annotations

import json
import subprocess
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

DEFAULT_COMMAND: tuple[str, ...] = (sys.executable, "-m", "sistent")


class ScanError(Exception):
    """con/sistent could not produce a report (for example, ``main`` could not be cloned)."""


def _toml_string(value: str) -> str:
    # The names are validated against the schema's patterns, so a JSON string is also a valid TOML basic string.
    return json.dumps(value)


def sistent_toml(main: str, repositories: Sequence[str], *, cache_dir: Path | None = None, jobs: int = 8) -> str:
    """A ``sistent.toml`` comparing every repository against ``main``, with con/sistent's default aspects.

    Each repository is named by its ``owner/name`` so that two organizations' repositories of the same name never
    collide; con/sistent still recognizes the bare name, which it derives from the URL.
    """
    lines = [
        "# Generated by sistence-scan from config.json; not meant to be edited.",
        "[sistent]",
        f"main = {_toml_string(main)}",
        'fail_on = "never"',
        f"jobs = {jobs}",
    ]
    if cache_dir is not None:
        lines.append(f"cache_dir = {_toml_string(str(cache_dir))}")
    for name in repositories:
        lines.extend(["", f"[repos.{_toml_string(name)}]", f"url = {_toml_string(name)}"])
    return "\n".join(lines) + "\n"


def run_sistent(config_path: Path, report_path: Path, *, command: Sequence[str] = DEFAULT_COMMAND) -> dict[str, Any]:
    """Run ``sistent check`` and return its JSON report.

    Findings and unavailable satellites are what the scan is for, so neither fails it; only a run that writes no
    report (main unavailable, a configuration error) raises :class:`ScanError`.
    """
    args = [
        *command,
        "check",
        "--config",
        str(config_path),
        "--format",
        "json",
        "--output",
        str(report_path),
        "--fail-on",
        "never",
        "--allow-unavailable",
    ]
    result = subprocess.run(args, capture_output=True, text=True, check=False)
    if result.returncode not in (0, 1) or not report_path.is_file():
        detail = (result.stderr or result.stdout).strip()
        raise ScanError(f"sistent exited with {result.returncode} without a report: {detail}")
    report: dict[str, Any] = json.loads(report_path.read_text(encoding="utf-8"))
    return report
